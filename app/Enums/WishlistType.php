<?php

namespace App\Enums;

/**
 * Тип списка.
 *
 * Gift — список желаний: позиции выбирают гости по ссылке.
 * Todo — список дел: доступен только владельцу, is_selected позиции
 * означает «выполнено», а ссылка, цена, приоритет и режим сюрприза не используются.
 * Note — заметка: доступна только владельцу, у неё нет названия и позиций,
 * а текст хранится в поле content.
 * Fund — сбор: позиции — цели со ссылкой на сбор на сторонней платформе
 * (config('wishlist.fund_hosts')) и необязательной целевой суммой в price.
 * Гости только переходят по ссылкам: выбора, броней и режима сюрприза нет.
 */
enum WishlistType: string
{
    case Gift = 'gift';
    case Todo = 'todo';
    case Note = 'note';
    case Fund = 'fund';
}
